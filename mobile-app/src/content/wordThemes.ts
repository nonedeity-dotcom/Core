export const themeById = (id: string): WordTheme | null => WORD_THEMES.find((t) => t.id === id) ?? null;

/** Открытая тема: бесплатная всегда, купленная — по списку купленного. */
export const themeOpen = (theme: WordTheme, owned: string[]): boolean =>
  theme.paid !== true || owned.includes(themeItemId(theme.id));

/** Идентификатор товара для темы. Одно правило в одном месте, чтобы строки не разъезжались. */
export const themeItemId = (themeId: string): string => `theme-${themeId}`;
