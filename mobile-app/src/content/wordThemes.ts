/**
 * Слова для «Найди слова», разложенные по темам.
 *
 * Полного словаря здесь нет и не нужно: человек не вводит свои слова, а ищет те, что уже
 * спрятаны, — значит, достаточно списка. Списки написаны от руки, поэтому и вопроса о
 * лицензии на чужой словарь не возникает.
 *
 * Правила для слов: только существительные в именительном падеже, от трёх до девяти букв,
 * без Ё (в поле она неотличима от Е и спор о том, засчитывать ли, не стоит того), без
 * дефисов и пробелов.
 */

