/**
 * The rotation, in the order it is walked. Numbered 1..N for the reader: the
 * counter advances every time the app is opened, so a visible number is the
 * only way to tell where in the loop you are.
 */
export const ROTATION = TIPS.filter((t) => t.rotate);

const ROTATION_NUMBERS = new Map(ROTATION.map((t, i) => [t.id, i + 1]));

/** 1-based position in the rotation, or null for reference-only tips. */
export function rotationNumber(tipId: string): number | null {
  return ROTATION_NUMBERS.get(tipId) ?? null;
}

export function tipsInSection(sectionId: string): Tip[] {
  return TIPS.filter((t) => t.section === sectionId);
}
