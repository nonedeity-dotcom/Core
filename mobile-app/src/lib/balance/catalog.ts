import type { Dish, FoodProduct } from "./food";

/**
 * Базовый набор: продукты, с которых можно начать, и несколько блюд из них.
 *
 * Готовой базы у CaloriX нет — так и задумано, — но пустой список означает, что первые
 * вечера уходят на ввод очевидного, а строка «400 г риса и 2 яйца» не узнаёт ничего. Это
 * не база продуктов мира: это стартовая полка на сорок позиций, которая после добавления
 * становится обычными своими продуктами — их можно править и удалять.
 *
 * **Числа ориентировочные, по справочникам.** У пачки в руках свои: жирность творога,
 * состав хлеба и порода рыбы гуляют на десятки процентов. Поэтому набор — точка отсчёта, а
 * не истина, и об этом сказано в самом приложении, а не только здесь.
 *
 * Отдельно про сырое и варёное. Сто граммов сухого риса и сто граммов отварного отличаются
 * втрое, и молчаливая подмена одного другим — самая дорогая ошибка, какую такой набор может
 * сделать. Поэтому состояние стоит прямо в названии, а привычная форма названа короче: при
 * разборе строки «риса» побеждает более короткое имя, и им должно быть то, что человек ест,
 * а не то, что лежит в пакете. Из-за того же правила уточнения к неосновным формам сделаны
 * длиннее основных («Макароны, сухая крупа», «Сливочное масло 82%»): короткое уточнение
 * перетягивало бы на себя обычный запрос.
 *
 * Названия разговорные, а не словарные: «Картошка», а не «Картофель». Ищется по тому, что
 * человек напечатает в телефоне вечером, а не по тому, как это зовут в справочнике.
 */

/** Продукт набора: то же, что обычный, но с заранее известным id — чтобы не задваивался. */
export type CatalogProduct = FoodProduct;

/** Блюдо набора: ссылки на продукты набора по их id. */
